// Command docsgen writes docs/reference/cli-flags.md from the command table
// that drives `pandora help` and `pandora <command> -h`, so the published
// flag reference cannot drift from the program. Run it from the repository
// root: go run ./scripts/docsgen. A test fails when the committed file is stale.
package main

import (
	"bytes"
	"fmt"
	"os"
	"strings"

	"github.com/RafaSG13/Pandora/internal/cli"
)

const output = "docs/reference/cli-flags.md"

// run executes one pandora invocation and returns what it printed.
func run(args ...string) string {
	var out, errb bytes.Buffer
	cli.Run(args, strings.NewReader(""), &out, &errb)
	return out.String() + errb.String()
}

// commandNames reads the command names from `pandora help`.
func commandNames(help string) []string {
	var names []string
	inList := false
	for _, line := range strings.Split(help, "\n") {
		switch {
		case line == "Commands:":
			inList = true
		case inList && strings.HasPrefix(line, "  "):
			if f := strings.Fields(line); len(f) > 0 && f[0] != "help" {
				names = append(names, f[0])
			}
		case inList:
			inList = false
		}
	}
	return names
}

// render builds the whole page.
func render() string {
	help := run("help")
	var b strings.Builder
	b.WriteString("# Command flags\n\n")
	b.WriteString("<!-- Generated by `go run ./scripts/docsgen` from the command table. Do not edit by hand. -->\n\n")
	b.WriteString("Every command and flag, exactly as `pandora help` and `pandora <command> -h` print them. ")
	b.WriteString("For what each command does, see the [command-line guide](cli.md).\n\n")
	b.WriteString("```text\n" + strings.TrimRight(help, "\n") + "\n```\n")
	for _, name := range commandNames(help) {
		fmt.Fprintf(&b, "\n## `pandora %s`\n\n```text\n%s\n```\n", name, strings.TrimRight(run(name, "-h"), "\n"))
	}
	return b.String()
}

func main() {
	if err := os.WriteFile(output, []byte(render()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "docsgen: %v\n", err)
		os.Exit(1)
	}
}
